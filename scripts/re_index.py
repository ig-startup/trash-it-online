"""
Rebuild docs/re/INDEX.md — one line per note: its title, how sure it is,
the routines it is mostly about, and the clone files that cite it.

The index is generated so it never drifts from the notes: add or edit a
note under docs/re/, then run

    python3 scripts/re_index.py

A note's title is its first line; its status is the bold word in it
(Confirmed, Inferred, Partly confirmed, Unsolved). Its key routines are
the routines it quotes most, by address or by `name`, named from scripts/ghidra/symbols*.
"""
import bisect
import collections
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(REPO, "docs", "re")
sys.path.insert(0, os.path.join(REPO, "scripts", "ghidra"))
from fn import WORK, HEAD, load_symbols, LIBRARY_LO  # noqa: E402

GROUPS = [
    ("formats", "File formats"),
    ("levels", "Levels"),
    ("jack", "Jack"),
    ("objects", "Objects and enemies"),
    ("logic", "Engine"),
    ("front", "Front end (F.EXE)"),
    ("tools", "Tools"),
    ("", "Open questions"),
]
CLONE = ["client/src", "server/src", "shared", "scripts"]
#: Notes whose addresses are not G.EXE's (F.EXE) or are only examples.
NO_KEY = ("front", "tools", "")
VA = re.compile(r"\b0x([0-9a-f]{5})\b")

HEADER = """\
# Reverse engineering notes — index

What the original Trash It (1997, DOS) does, read from its own code and
files. One note per topic; read this index, then only the note you need.
Background and method: [about.md](about.md).

**Status:** C confirmed (from the code, checked by rendering or replay) ·
I inferred (fits every sample, not traced) · P partly confirmed · U unsolved.
**Key code:** the routines a note quotes most, as `name 0xVA` —
`python3 scripts/ghidra/fn.py show <name>` prints one.
**Clone:** files under `client/`, `server/`, `shared/`, `scripts/` that
cite the note.

The notes were one file once: "above", "below" or "the X section" in a
note means another note — find X's title here.

Generated by `scripts/re_index.py` — edit the notes, not this file.
"""


def status(title):
    for word, code in (("Partly confirmed", "P"), ("Confirmed", "C"),
                       ("Inferred", "I"), ("Unsolved", "U")):
        if "**%s" % word in title:
            return code
    return "–"


def clean(title):
    t = title.lstrip("# ")
    t = re.sub(r"\s+—\s+\*\*.*$", "", t)
    return t.replace("`", "")


def cited_by(rel):
    r = subprocess.run(["git", "grep", "--untracked", "-l", "-F", "docs/re/" + rel, "--"] + CLONE,
                       cwd=REPO, capture_output=True, text=True)
    return sorted(os.path.basename(p) for p in r.stdout.split()
                  if p not in ("scripts/re_index.py", "scripts/formats/README.md"))


def function_starts():
    """Every function entry in the decompilation, named or not; without
    one, only the named entries (and then only exact hits count)."""
    path = os.path.join(WORK, "decomp.c")
    if os.path.exists(path):
        text = open(path, encoding="utf-8", errors="replace").read()
        return sorted(int(m.group(2), 16) for m in HEAD.finditer(text)), True
    return sorted(load_symbols()), False


def main():
    syms = load_symbols()
    starts, whole = function_starts()
    by_name = {n: a for a, n in syms.items()}

    def owner(a):
        # the function an address is in, if it has a name
        i = bisect.bisect_right(starts, a) - 1
        o = starts[i] if i >= 0 and (whole or starts[i] == a) else None
        return o if o in syms else None

    notes = collections.defaultdict(list)
    for root, _dirs, files in os.walk(DOCS):
        for f in sorted(files):
            if not f.endswith(".md") or f in ("INDEX.md", "about.md"):
                continue
            path = os.path.join(root, f)
            rel = os.path.relpath(path, DOCS)
            text = open(path, encoding="utf-8").read()
            title = text.split("\n", 1)[0]
            counts = collections.Counter()
            for m in ([] if os.path.dirname(rel) in NO_KEY else VA.finditer(text)):
                a = int(m.group(1), 16)
                if 0x10000 <= a < LIBRARY_LO:
                    o = owner(a)
                    if o is not None:
                        counts[o] += 1
            if os.path.dirname(rel) not in NO_KEY:
                for m in re.finditer(r"`([a-z_][a-z0-9_]+)`", text):
                    if m.group(1) in by_name:
                        counts[by_name[m.group(1)]] += 1
            key = ", ".join("%s 0x%x" % (syms[a], a) for a, _n in counts.most_common(3))
            group = os.path.dirname(rel)
            notes[group].append((rel, clean(title), status(title), key, cited_by(rel),
                                 (len(text) + 512) // 1024))

    out = [HEADER]
    for group, name in GROUPS:
        if not notes.get(group):
            continue
        out.append("## %s\n" % name)
        for rel, title, st, key, clone, kb in notes.pop(group):
            line = "- [%s](%s) %s %dK" % (title, rel, st, max(kb, 1))
            if key:
                line += " · %s" % key
            if clone:
                line += " · clone: %s" % ", ".join(clone)
            out.append(line)
        out.append("")
    if notes:
        sys.exit("notes in a folder GROUPS does not list: %s" % sorted(notes))
    with open(os.path.join(DOCS, "INDEX.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(out))
    print("docs/re/INDEX.md: %d bytes" % len("\n".join(out).encode()))


if __name__ == "__main__":
    main()
